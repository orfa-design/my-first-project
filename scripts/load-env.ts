// Скрипти запускаються поза Next.js, тому .env.local треба підвантажити самостійно.
// Змінні, вже задані в середовищі (наприклад, секрети хмарної сесії), мають пріоритет.
for (const file of [".env.local", ".env"]) {
  try {
    process.loadEnvFile(file);
  } catch {
    // файлу немає — це нормально
  }
}
